// campaign_report.js drives the standalone, printable campaign report page.
// It pulls the campaign's aggregated, PII-free metrics and descriptive context
// from the report endpoint, then renders the audit header, data-protection
// statement, funnel tiles, engagement timeline, and time-to-engage table. The
// campaign id and build version are injected by the server as the globals
// `campaignId` and `gophishVersion`.

// formatPct turns a fraction in [0, 1] into a one-decimal percentage.
function formatPct(fraction) {
    return (fraction * 100).toFixed(1) + "%"
}

// isRealDate reports whether a timestamp from the API is a genuine date rather
// than Go's zero value, which serializes as year 0001 for never-set fields
// like a not-yet-completed campaign's completed_date.
function isRealDate(ts) {
    return ts && moment(ts).year() > 1
}

// fmtDate renders a timestamp in the report's consistent format, or an em dash
// when it isn't a real date.
function fmtDate(ts) {
    return isRealDate(ts) ? moment(ts).format("MMM D, YYYY h:mm a") : "—"
}

// formatDuration renders a Go time.Duration (nanoseconds) as a compact,
// human-readable string using at most the two most significant units. A zero
// duration (e.g. a stage nobody reached) renders as an em dash.
function formatDuration(ns) {
    if (!ns) {
        return "—"
    }
    var totalSeconds = Math.round(ns / 1e9)
    var d = moment.duration(totalSeconds, "seconds")
    var units = [
        [Math.floor(d.asDays()), "d"],
        [d.hours(), "h"],
        [d.minutes(), "m"],
        [d.seconds(), "s"]
    ]
    var parts = []
    for (var i = 0; i < units.length && parts.length < 2; i++) {
        if (units[i][0] > 0 || parts.length > 0) {
            parts.push(units[i][0] + units[i][1])
        }
    }
    return parts.length ? parts.join(" ") : "0s"
}

// reportID builds a stable, human-citable identifier for this printout from
// the campaign id and the generation time.
function reportID(generatedAt) {
    return "CR-" + campaignId + "-" + generatedAt.format("YYYYMMDD-HHmm")
}

// renderMeta fills the header title, status, and anonymized badge.
function renderMeta(meta, anonymized) {
    $("#report-title").text(meta.name + " – Report")
    document.title = meta.name + " - Report - Gophish-NG"
    $("#report-meta").html("<span><b>Status:</b> " + meta.status + "</span>")
    if (anonymized) {
        $("#anonymized_badge").show()
    }
}

// renderAuditHeader renders the evidence/audit block: what was tested, by
// whom, when, and with which build - so the printout stands on its own.
function renderAuditHeader(meta, generatedAt) {
    var rows = [
        ["Report ID", reportID(generatedAt)],
        ["Campaign", meta.name],
        ["Status", meta.status],
        ["Template", meta.template_name],
        ["Sending profile", meta.smtp_name],
        ["Launched", fmtDate(meta.launch_date)],
        ["Completed", fmtDate(meta.completed_date)],
        ["Generated", generatedAt.format("MMM D, YYYY h:mm a")],
        ["Generated by", typeof user !== "undefined" ? user.username : "—"],
        ["Gophish version", typeof gophishVersion !== "undefined" ? gophishVersion : "—"]
    ]
    var html = ""
    rows.forEach(function (r) {
        html += "<dt>" + r[0] + "</dt><dd>" + $("<div>").text(r[1]).html() + "</dd>"
    })
    $("#audit-header").html(html)
}

// renderDataProtection states the report's data-protection posture. The report
// is always aggregate-only; an anonymized campaign additionally had recipient
// PII scrubbed at rest, which is called out with its date as evidence.
function renderDataProtection(meta, anonymized) {
    var items = [
        "This report contains only aggregate metrics – no recipient names, addresses, or submitted data."
    ]
    if (anonymized) {
        items.push("Campaign anonymized on " + fmtDate(meta.scrubbed_date) +
            " – recipient-identifying data was scrubbed at rest.")
        items.push("Results cannot be attributed to individual recipients.")
    }
    var html = ""
    items.forEach(function (text) {
        html += "<li>" + text + "</li>"
    })
    $("#data-protection").html(html)
    $("#data-protection-card").show()
}

// renderExecutiveSummary writes the one-line management takeaway. Before any
// mail has gone out there's nothing to summarize, so it says so instead of
// reporting a stream of 0%.
function renderExecutiveSummary(stats, rates) {
    var text
    if (!stats.sent) {
        text = "This campaign has not sent any emails yet."
    } else {
        text = "Of " + stats.total + " recipients, " + formatPct(rates.click) +
            " clicked the phishing link and " + formatPct(rates.report) +
            " reported the email."
    }
    $("#executive-summary").text(text)
}

// renderNoInteraction reports recipients who never even opened the email,
// completing the funnel's picture of coverage.
function renderNoInteraction(stats) {
    if (!stats.total) {
        return
    }
    var noInteraction = Math.max(stats.total - stats.opened, 0)
    var rate = noInteraction / stats.total
    $("#no-interaction").html("<b>No interaction:</b> " + noInteraction + " (" +
        formatPct(rate) + ") of " + stats.total + " recipients never opened the email.")
}

// renderTiles renders one funnel tile per stage, each showing the absolute
// count and its rate relative to the total recipient count.
function renderTiles(stats, rates) {
    var sentRate = stats.total ? stats.sent / stats.total : 0
    var tiles = [
        { label: "Sent", value: stats.sent, rate: sentRate },
        { label: "Opened", value: stats.opened, rate: rates.open },
        { label: "Clicked", value: stats.clicked, rate: rates.click },
        { label: "Submitted Data", value: stats.submitted_data, rate: rates.submit },
        { label: "Reported", value: stats.email_reported, rate: rates.report }
    ]
    var html = ""
    tiles.forEach(function (t) {
        html += '<div class="stat-tile">' +
            '<div class="stat-value">' + t.value + '</div>' +
            '<div class="stat-rate">' + formatPct(t.rate) + '</div>' +
            '<div class="stat-label">' + t.label + '</div>' +
            '</div>'
    })
    $("#stat-tiles").html(html)
}

// renderResilience surfaces the positive-behavior indicator: how many reports
// were made relative to clicks. A higher ratio means recipients recognized and
// reported the phish rather than falling for it. Reports and clicks are
// independent aggregates, so this is a program-level ratio, not a subset.
function renderResilience(stats) {
    var text
    if (stats.clicked > 0) {
        var ratio = stats.email_reported / stats.clicked
        text = "<b>Resilience:</b> " + stats.email_reported + " reported vs " +
            stats.clicked + " clicked (" + formatPct(ratio) + " report-to-click ratio). " +
            "A higher ratio means more recipients recognized and reported the phish."
    } else {
        text = "<b>Resilience:</b> " + stats.email_reported +
            " reported; no clicks recorded."
    }
    $("#resilience").html(text)
}

// renderTimeline draws cumulative engagement (opens, clicks, submissions) over
// time as lines - the classic "how fast did recipients fall for it" curve.
// With no engagement events there's nothing to plot, so it shows a message in
// place of empty axes.
function renderTimeline(timeline) {
    if (!timeline.length) {
        $("#timeline_chart").hide()
        $("#timeline-empty").show()
        return
    }

    var chart = echarts.init(document.getElementById("timeline_chart"))
    var opened = []
    var clicked = []
    var submitted = []
    var co = 0, cc = 0, cs = 0
    timeline.forEach(function (b) {
        co += b.opened
        cc += b.clicked
        cs += b.submitted
        opened.push([b.time, co])
        clicked.push([b.time, cc])
        submitted.push([b.time, cs])
    })
    var series = function (name, data) {
        return {
            name: name,
            type: "line",
            smooth: true,
            symbol: "circle",
            symbolSize: 5,
            data: data
        }
    }
    chart.setOption({
        tooltip: {
            trigger: "axis",
            formatter: function (params) {
                var lines = [moment(params[0].value[0]).format("MMM D, h:mm a")]
                params.forEach(function (p) {
                    lines.push(p.marker + p.seriesName + ": <b>" + p.value[1] + "</b>")
                })
                return lines.join("<br>")
            }
        },
        legend: { data: ["Opened", "Clicked", "Submitted Data"], top: 0 },
        grid: { top: 40, bottom: 30, left: "1%", right: "2%", containLabel: true },
        xAxis: { type: "time" },
        yAxis: { type: "value", minInterval: 1, name: "cumulative" },
        series: [
            series("Opened", opened),
            series("Clicked", clicked),
            series("Submitted Data", submitted)
        ]
    })
    // The report can be printed, and the chart needs to resize with the page.
    $(window).on("resize", function () {
        chart.resize()
    })
}

// renderTiming fills the time-to-engage table, one row per stage.
function renderTiming(timing) {
    var rows = [
        { label: "Opened", stage: timing.open },
        { label: "Clicked", stage: timing.click },
        { label: "Submitted Data", stage: timing.submit }
    ]
    var html = ""
    rows.forEach(function (r) {
        html += "<tr>" +
            "<td>" + r.label + "</td>" +
            '<td class="text-end">' + r.stage.count + "</td>" +
            '<td class="text-end">' + formatDuration(r.stage.median) + "</td>" +
            '<td class="text-end">' + formatDuration(r.stage.average) + "</td>" +
            "</tr>"
    })
    $("#timing-table tbody").html(html)
}

$(document).ready(function () {
    api.campaignId.reportData(campaignId).done(function (report) {
        var generatedAt = moment()

        renderMeta(report.meta, report.anonymized)
        renderExecutiveSummary(report.stats, report.rates)
        renderAuditHeader(report.meta, generatedAt)
        renderDataProtection(report.meta, report.anonymized)
        renderTiles(report.stats, report.rates)
        renderNoInteraction(report.stats)
        renderResilience(report.stats)
        renderTiming(report.timing)
        renderTimeline(report.timeline || [])

        $("#loading").hide()
        $("#report").show()
        // echarts needs a layout pass after the container becomes visible.
        $(window).trigger("resize")
    }).fail(function () {
        $("#loading").hide()
        errorFlash("Error fetching campaign report")
    })
})
